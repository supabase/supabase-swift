-- PostgrestModifiersIntegrationTests.
--
-- `explain()` sends `Accept: application/vnd.pgrst.plan`, which PostgREST refuses unless
-- `db-plan-enabled` is on. Aggregates (`sum()`, `avg()`, `@Aggregate`) need
-- `db-aggregates-enabled`. The CLI has no setting for either, so set them on the role PostgREST
-- connects as, as `pgrst.db_tx_end` is set in the initial migration.
ALTER ROLE authenticator SET pgrst.db_plan_enabled TO 'true';
ALTER ROLE authenticator SET pgrst.db_aggregates_enabled TO 'true';

-- A schema outside `public`, exposed in config.toml (`api.schemas`), so `schema(_:)` can prove
-- that `Accept-Profile` and `Content-Profile` reach it.
CREATE SCHEMA IF NOT EXISTS personal;
GRANT USAGE ON SCHEMA personal TO anon, authenticated, service_role;

CREATE TABLE personal.notes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  body TEXT NOT NULL
);

GRANT ALL ON TABLE personal.notes TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE personal.notes_id_seq TO anon, authenticated, service_role;

-- `geojson()` asks for `application/geo+json`, which PostgREST builds only for a relation with a
-- PostGIS geometry column.
CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA extensions;

CREATE TABLE personal.places (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  location extensions.geometry(Point, 4326) NOT NULL
);

INSERT INTO personal.places (id, name, location) VALUES
  (1, 'origin', extensions.ST_SetSRID(extensions.ST_MakePoint(0, 0), 4326)),
  (2, 'harbor', extensions.ST_SetSRID(extensions.ST_MakePoint(-9.14, 38.72), 4326));

GRANT SELECT ON TABLE personal.places TO anon, authenticated, service_role;

NOTIFY pgrst, 'reload config';
NOTIFY pgrst, 'reload schema';
